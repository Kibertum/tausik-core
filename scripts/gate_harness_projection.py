"""Refuse committing generated TAUSIK harness copies into a project tree.

Owner rule (release 1.13.2 dogfooding): a consumer project's git history must
carry the project's own code plus the `tausik/` state export — not the
bootstrap-deployed IDE profile trees, not machine-local MCP launcher JSON, and
not the insides of `.tausik-lib/` treated as ordinary files. Those copies are
regenerated by bootstrap; committing them re-drags the framework into every
push and breaks the next host on a different machine.

The gate reads the INDEX (`git diff --cached`), not the working tree: a
gitignored profile is invisible until someone force-adds it, and that force-add
is exactly the defect to stop.
"""

from __future__ import annotations

import os
import sqlite3
import subprocess
import sys
from typing import Any

import gate_outcome
import git_exec
from gate_spec import PHASE_SCOPED, GateSpec

_EXTRA_PROFILE_DIRS = frozenset({".agents", ".kilocode", ".claude-project"})
_MACHINE_LOCAL_FILES = frozenset({".mcp.json", "opencode.json", ".cursorrules"})
# Consumer marker: `.tausik-lib` present means framework code arrives via a
# local checkout (submodule or vendor copy). Staging the framework's own trees
# beside it — or the checkout itself — is the "drag the framework into the
# project" defect that keeps recurring. The core repository has no
# `.tausik-lib`, so these prefixes stay legitimate there.
_CONSUMER_FRAMEWORK_PREFIXES = (
    "bootstrap/",
    "harness/",
    "scripts/hooks/",
    ".tausik/",
    ".tausik-lib/",
)
# Project state export is the only TAUSIK tree that belongs in consumer git.
_CONSUMER_ALLOWED_PREFIXES = ("tausik/",)
_MISSING_EXPORT_STDERR = (
    "harness_projection: DB has project state, but this commit stages no "
    "`tausik/` export. Durable tracked TAUSIK surface is `tausik/` "
    "(run `tausik state export` and `git add tausik/`), not `.tausik-lib` "
    "or deployed IDE/harness trees.\n"
)

HARNESS_PROJECTION_SPEC = GateSpec(
    name="harness_projection",
    prevents=(
        "A commit lands that re-drags generated IDE harness copies, machine-local "
        "MCP launchers, or unpacked `.tausik-lib/` files into the project history — "
        "the shape that turns every upgrade into a framework dump instead of a "
        "`tausik/` export. "
    ),
    phase=PHASE_SCOPED,
    impl="gate_harness_projection:run_harness_projection_gate_for",
    default_config={
        "enabled": True,
        "severity": "block",
        "trigger": ["commit"],
        "command": None,
        "description": (
            "Fail if staged paths are generated IDE harness, machine-local "
            "MCP JSON, or unpacked .tausik-lib contents"
        ),
    },
)


def _repo_root() -> str:
    try:
        from project_config import find_tausik_dir

        return os.path.dirname(os.path.abspath(find_tausik_dir()))
    except Exception:  # noqa: BLE001 — fall back to cwd when no project handle
        return os.getcwd()


def _git(root: str, *args: str) -> subprocess.CompletedProcess | None:
    try:
        return git_exec.run_git(
            ["git", *args],
            cwd=root,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=20,
            check=False,
            stdin=subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError):
        return None


def _profile_prefixes() -> tuple[str, ...]:
    # Always via ide_utils. A hardcoded profile-name fallback fails the
    # multi-IDE literal lint (TestNoNewClaudeLiterals) and would silently
    # cover only a subset of hosts if the registry grew.
    from ide_utils import all_profile_dirs

    dirs = set(all_profile_dirs()) | _EXTRA_PROFILE_DIRS
    return tuple(sorted(f"{d}/" for d in dirs if d))


def _consumer_has_lib(root: str) -> bool:
    return os.path.exists(os.path.join(root, ".tausik-lib"))


def _db_has_state(root: str) -> bool:
    """True when the project DB exists and holds at least one durable row."""
    db = os.path.join(root, ".tausik", "tausik.db")
    if not os.path.isfile(db):
        return False
    try:
        conn = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        try:
            for table in ("tasks", "memory", "decisions"):
                try:
                    n = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
                except sqlite3.Error:
                    continue
                if n and int(n) > 0:
                    return True
            return False
        finally:
            conn.close()
    except (OSError, sqlite3.Error):
        return False


def _staged_has_export(staged: list[str]) -> bool:
    for raw in staged:
        path = raw.replace("\\", "/")
        if path == "tausik" or path.startswith("tausik/"):
            return True
    return False


def _warn_missing_export(root: str, staged: list[str]) -> None:
    """Stderr notice when durable state exists but the commit omits tausik/."""
    if not _consumer_has_lib(root):
        return
    if not _db_has_state(root):
        return
    if _staged_has_export(staged):
        return
    sys.stderr.write(_MISSING_EXPORT_STDERR)


def _shadows_lib_checkout(root: str, path: str) -> bool:
    """True when a nested staged path already exists inside `.tausik-lib`.

    Agents repeatedly copy framework trees from the submodule into the project
    root (`scripts/project.py`, `docs/en/…`, …). Prefix lists cannot name every
    future file; if the same relative nested path lives under `.tausik-lib`,
    staging it at the project root is framework contamination — except the
    `tausik/` export.

    Root-level basenames are project-owned surface even when the library ships
    the same name (AGENTS.md, README.md, CLAUDE.md, …). Same basename alone is
    not harness contamination; only a nested path that shadows the lib tree is.
    """
    if path == ".tausik-lib" or path.startswith(".tausik-lib/"):
        return False
    if path == "tausik" or any(
        path == p.rstrip("/") or path.startswith(p) for p in _CONSUMER_ALLOWED_PREFIXES
    ):
        return False
    # Project-owned root docs share names with the library checkout; never treat
    # a single-segment path as a harness shadow of `.tausik-lib`.
    if "/" not in path:
        return False
    return os.path.lexists(os.path.join(root, ".tausik-lib", *path.split("/")))


def forbidden_staged_paths(
    staged: list[str],
    *,
    consumer: bool = False,
    root: str | None = None,
) -> list[str]:
    """Return staged paths that drag generated harness / lib contents into git."""
    prefixes = _profile_prefixes()
    bad: list[str] = []
    for raw in staged:
        path = raw.replace("\\", "/")
        if path in _MACHINE_LOCAL_FILES:
            bad.append(path)
            continue
        if path == ".tausik" or path.startswith(".tausik/"):
            bad.append(path)
            continue
        if any(path == p.rstrip("/") or path.startswith(p) for p in prefixes):
            bad.append(path)
            continue
        # Export-only: refuse both unpacked lib files and the checkout pointer
        # on consumers. Non-consumer (framework) trees never stage `.tausik-lib`.
        if path == ".tausik-lib" or path.startswith(".tausik-lib/"):
            bad.append(path)
            continue
        if consumer and any(
            path == p.rstrip("/") or path.startswith(p) for p in _CONSUMER_FRAMEWORK_PREFIXES
        ):
            bad.append(path)
            continue
        if consumer and root and _shadows_lib_checkout(root, path):
            bad.append(path)
    return bad


def run_harness_projection_gate_for(gate: dict[str, Any], files: list[str]):
    """Registry entrypoint — `files` ignored; the INDEX is the subject."""
    del gate, files
    root = _repo_root()
    got = _git(root, "diff", "--cached", "--name-only")
    if got is None or got.returncode != 0:
        return gate_outcome.could_not_run(
            gate_outcome.REASON_RUNNER_ERROR,
            "harness_projection: staged file list could not be read (no git or no repository).",
            remedy="Run the commit from inside the git repository with git on PATH.",
        )
    staged = [ln.strip() for ln in (got.stdout or "").splitlines() if ln.strip()]
    if not staged:
        return gate_outcome.not_applicable(
            "no_staged_files",
            "harness_projection: nothing staged — nothing to refuse.",
            remedy="Stage the project change and the tausik/ export, then re-run.",
        )
    _warn_missing_export(root, staged)
    bad = forbidden_staged_paths(staged, consumer=_consumer_has_lib(root), root=root)
    if not bad:
        return gate_outcome.passed(
            "harness_projection: staged set has no generated IDE harness, "
            "machine-local MCP launcher, framework trees beside `.tausik-lib`, "
            "nested paths that shadow `.tausik-lib`, or `.tausik-lib` itself "
            "(root docs such as AGENTS.md/README.md stay project-owned)."
        )
    shown = "\n  ".join(bad[:20])
    more = f"\n  … (+{len(bad) - 20} more)" if len(bad) > 20 else ""
    return gate_outcome.failed(
        "harness_projection: refusing to commit generated TAUSIK harness "
        f"copies ({len(bad)} path(s)). Ownership signal: project git carries "
        "product code plus `tausik/` export — not IDE profile trees, not "
        "opencode/.mcp machine paths, not `.tausik/` runtime, not "
        "bootstrap/harness/hooks beside `.tausik-lib`, not nested paths that "
        "already exist under `.tausik-lib` (root AGENTS.md/README.md are "
        "project-owned and are not refused for a matching lib basename), and "
        "not `.tausik-lib/` itself:\n  "
        f"{shown}{more}\n"
        "Fix: git restore --staged <harness paths>; keep project docs staged; "
        "ensure harness trees are in .gitignore; run `tausik state export` "
        "and `git add tausik/` for project state."
    )
