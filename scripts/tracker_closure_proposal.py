"""Закрытие задачи ПРЕДЛАГАЕТ ответить в тикет — и никогда не отвечает само.

НЕДОСТАЮЩИЙ ШАГ, А НЕ ЗАБЫВЧИВОСТЬ. Пока связи задача-тикет не было как данных,
в процедуре закрытия неоткуда было взяться вопросу «а не пришла ли эта задача из
внешнего трекера». Одиннадцать открытых тикетов обоих трекеров — цена этого
отсутствия, и разбирали её вручную (смена #189).

ПОЧЕМУ ТОЛЬКО ТЕКСТ. Отрицательное требование задачи названо прямо: не
автоматизировать закрытие БЕЗ подтверждения человеком. Тикет мог описывать
больше, чем закрыла задача, — тогда автозакрытие обрубает чужую находку на
половине. Тихое закрытие чужого тикета хуже незакрытого: незакрытый виден.

ПОЧЕМУ ТЕКСТ ГОВОРИТ ПРО ДОСТИЖИМОСТЬ, А НЕ ПРОСТО «ЗАКРОЙ С SHA». Это вывод
ручного разбора, добытый проверкой, а не осторожностью: ни один из четырёх
коммитов-исправлений (`056818b`, `3de2528`, `b487f87`, `5a58b50`) не достижим ни
из `github/main`, ни из `github/release/1.9`. Для автора тикета, у которого есть
только публичный репозиторий, ссылка на такой SHA — ссылка в никуда. Напоминание,
которое советовало бы закрыть тикет по коммиту ветки разработки, воспроизводило
бы ровно ту ошибку, которую разбор обошёл.

СЕТИ ЗДЕСЬ НЕТ. Модуль складывает строку. Он не знает ни хоста, ни токена, ни
того, открыт ли тикет: спросить об этом значило бы завести в закрытие задачи
сетевой вызов, который однажды не ответит, — и закрытие встанет из-за трекера.
"""

from __future__ import annotations

import tracker_ref


def proposal_for(refs: list[str]) -> str | None:
    """Текст напоминания, либо ``None``, когда напоминать не о чем.

    ``None`` — это AC-4: задача без привязки к трекеру не получает при закрытии
    ни одной новой строки. Напоминание, печатающееся всем, читается всеми как
    шум и через неделю не читается никем.
    """
    if not refs:
        return None
    listed = ", ".join(refs)
    # Число НЕ подставляется в эту фразу намеренно. Русское согласование по
    # количеству (1 тикет / 2 тикета / 5 тикетов, плюс исключение для 11-14) —
    # три ветки и оговорка ради слова, которое ничего не сообщает: сами ссылки
    # перечислены следующей строкой, и их видно. Первая версия напечатала
    # «1 тикета» на первом же живом закрытии.
    subject = "Тикеты" if len(refs) > 1 else "Тикет"
    return (
        f"\nВНЕШНИЙ ТРЕКЕР: задача закрыта. {subject} — НЕТ:\n"
        f"  {listed}\n"
        "  Закрытие задачи ничего никуда не отправило и ничей тикет не тронуло.\n"
        "  Прежде чем закрывать: исправление должно быть ДОСТИЖИМО там, где его\n"
        "  видит автор тикета. Коммит ветки разработки для человека снаружи —\n"
        "  ссылка в никуда; отвечать SHA имеет смысл по публикации релиза.\n"
        "  Проверить: git merge-base --is-ancestor <sha> <публичная-ветка>\n"
        "  Тикет мог описывать БОЛЬШЕ, чем закрыла задача, — тогда ответить и\n"
        "  оставить открытым честнее, чем закрыть."
    )


def proposal_for_task(task: dict) -> str | None:
    """То же, но от строки задачи: читает поле и молчит на испорченном значении.

    Чтение через `tracker_ref.loads`, который на испорченном JSON возвращает
    пусто, а не падает: поле заведено ради долгов перед людьми и не смеет стать
    новым способом не закрыть работу.
    """
    return proposal_for(tracker_ref.loads(task.get("tracker_refs")))
